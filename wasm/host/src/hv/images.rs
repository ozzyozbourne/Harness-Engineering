    /// Boots the candidate and runs its own self-test export.
    fn boot_and_self_test(&self, component: &wasmtime::component::Component, version: u32) -> Result<String, (&'static str, String)> {
        let dir = ScratchDir::new();
        let env = self.scratch_env(&dir.0, Box::new(Mock::new(vec![]))).map_err(|e| ("boot", e))?;
        let mut inst = Instance::boot(component, version, env, self.limits.clone()).map_err(|f| ("boot", f.report))?;
        match inst.self_test() {
            Ok(Ok(summary)) => Ok(summary),
            Ok(Err(e)) => Err(("self-test", e)),
            Err(f) => Err(("self-test", f.report)),
        }
    }

    /// The hypervisor's own check that SPEC behavior holds: a mock task that
    /// uses a seed tool, proposes a tool and calls it in the same task; the
    /// journal; and replay in a second instance.
    fn conformance(&self, component: &wasmtime::component::Component, version: u32) -> Result<String, String> {
        let tool_use = |id: &str, name: &str, input: Value| json!([{"type": "tool_use", "id": id, "name": name, "input": input}]);
        let mock = Mock::new(vec![
            tool_use("c1", "word_count", json!({"text": "one two three"})),
            tool_use(
                "c2",
                "propose_def",
                json!({"name": "reverse", "kind": "tool", "source": REVERSE, "description": "reverses text",
                "tests": [{"input": {"text": "abc"}, "expect": "cba"}],
                "input_schema": {"type": "object", "properties": {"text": {"type": "string"}}, "required": ["text"]}}),
            ),
            tool_use("c3", "reverse", json!({"text": "stressed"})),
            json!([{"type": "text", "text": "conformance done"}]),
        ]);
        let reqs = mock.requests();
        let dir = ScratchDir::new();
        let env = self.scratch_env(&dir.0, Box::new(mock))?;
        let fail = |what: String| Err(format!("conformance: {what}"));
        let mut inst = Instance::boot(component, version, env.clone(), self.limits.clone()).map_err(|f| f.report)?;
        let out = inst.run_task("conformance: count words, then make and use a reverse tool").map_err(|f| f.report)?;
        if inst.base_prompt_inserted() {
            return fail("the image did not send the base prompt as its first system block".into());
        }
        if !out.success || out.answer != "conformance done" {
            return fail(format!(
                "the mock task should succeed with answer \"conformance done\"; got success={} answer={:?} error={:?}",
                out.success, out.answer, out.error
            ));
        }
        let reqs = reqs.lock().unwrap_or_else(|e| e.into_inner()).clone();
        if reqs.len() != 4 {
            return fail(format!("expected 4 model requests, got {}", reqs.len()));
        }
        let tool_names = |r: &Value| -> Vec<String> {
            r["tools"].as_array().into_iter().flatten().filter_map(|t| t["name"].as_str().map(String::from)).collect()
        };
        for t in
            ["bash", "read_file", "write_file", "list_defs", "show_def", "propose_def", "rollback_def", "remember", "recall", "word_count"]
        {
            if !tool_names(&reqs[0]).iter().any(|n| n == t) {
                return fail(format!("tool `{t}` missing from the first request's tool list"));
            }
        }
        if !tool_names(&reqs[2]).iter().any(|n| n == "reverse") {
            return fail("the proposed tool `reverse` is not in the tool list of the next request (late binding)".into());
        }
        let last_result = |r: &Value| -> String {
            r["messages"]
                .as_array()
                .into_iter()
                .flatten()
                .rev()
                .flat_map(|m| m["content"].as_array().cloned().unwrap_or_default())
                .find(|b| b["type"] == "tool_result")
                .map(|b| b["content"].as_str().unwrap_or("").to_string())
                .unwrap_or_default()
        };
        let checks = [
            (1, "3", "word_count of \"one two three\""),
            (2, "trial v1", "propose_def reverse"),
            (3, "desserts", "reverse of \"stressed\""),
        ];
        for (i, want, what) in checks {
            let got = last_result(&reqs[i]);
            if !got.starts_with(want) {
                return fail(format!("{what} should give {want:?}, got {:?}", first_line(&got, 200)));
            }
        }
        let events = env.journal.lock().unwrap_or_else(|e| e.into_inner()).read_all()?;
        let has = |kind: &str, f: &dyn Fn(&Value) -> bool| events.iter().any(|e| e["type"] == kind && f(e));
        if !has("task_started", &|_| true) || !has("task_finished", &|e| e["success"] == true) {
            return fail("the journal needs task_started and a successful task_finished".into());
        }
        if !has("def_trial", &|e| e["name"] == "reverse") || !has("def_use", &|e| e["name"] == "reverse" && e["ok"] == true) {
            return fail("the journal needs def_trial and a clean def_use for `reverse`".into());
        }
        let state1 = inst.command("/state").map_err(|f| f.report)?.map_err(|e| format!("conformance: /state: {e}"))?;
        drop(inst);
        let mut again = Instance::boot(component, version, env, self.limits.clone()).map_err(|f| f.report)?;
        let state2 = again.command("/state").map_err(|f| f.report)?.map_err(|e| format!("conformance: /state: {e}"))?;
        if state1 != state2 {
            return fail("a second instance replaying the journal does not reach the same state".into());
        }
        Ok("conformance passed (mock task, late binding, journal, replay)".into())
    }
