/// The built-in kernel image and its source (generated by build.rs).
pub const BUILTIN_WASM: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/cmh_guest.wasm"));
include!(concat!(env!("OUT_DIR"), "/kernel_files.rs"));

const BUILD_TIMEOUT: Duration = Duration::from_secs(900);
const COMPILER_OUTPUT_MAX: usize = 8 * 1024;

#[derive(Clone, Debug)]
pub struct ImageRec {
    pub version: u32,
    pub parent: u32,
    /// builtin, proposed, rejected, trial, kept, reverted.
    pub status: String,
    pub description: String,
    pub reason: String,
    pub size: u64,
    pub build_ms: u64,
    /// Clean tasks counted while it is `trial`.
    pub clean_tasks: u32,
}

/// Where image builds happen. Shared by every state dir: `target` keeps the
/// compiled dependencies, `build-src` is the scratch copy being built.
#[derive(Clone, Debug)]
pub struct BuildCfg {
    pub cache_dir: PathBuf,
    /// Paths a build may not write: the repository (hypervisor source, the
    /// evals) and the state dir.
    pub read_only: Vec<PathBuf>,
}

impl BuildCfg {
    /// `$CMH_IMAGE_CACHE`, else `$XDG_CACHE_HOME/cmh-wasm`, else `~/.cache/cmh-wasm`.
    pub fn default_cache_dir() -> PathBuf {
        let env = |k: &str| std::env::var(k).ok().filter(|v| !v.is_empty()).map(PathBuf::from);
        env("CMH_IMAGE_CACHE")
            .or_else(|| env("XDG_CACHE_HOME").map(|d| d.join("cmh-wasm")))
            .or_else(|| env("HOME").map(|h| h.join(".cache/cmh-wasm")))
            .unwrap_or_else(|| std::env::temp_dir().join("cmh-wasm-cache"))
    }
}

pub struct Images {
    pub recs: Vec<ImageRec>,
    pub live: u32,
    soak: u32,
    state_dir: PathBuf,
    journal: Arc<Mutex<Journal>>,
    build: BuildCfg,
    /// Settings for scratch instances (candidate tests).
    base_prompt: String,
    kernel_dir: PathBuf,
    limits: Limits,
}

fn trace(line: &str) {
    eprintln!("{line}");
}

fn first_line(s: &str, max: usize) -> String {
    let l = s.lines().find(|l| !l.trim().is_empty()).unwrap_or("").trim();
    if l.chars().count() <= max { l.to_string() } else { format!("{}...", l.chars().take(max).collect::<String>()) }
}

fn sh_quote(p: &Path) -> String {
    format!("'{}'", p.to_string_lossy().replace('\'', r"'\''"))
}

/// Copies a source tree (skipping `target/`).
fn copy_tree(from: &Path, to: &Path) -> Result<(), String> {
    std::fs::create_dir_all(to).map_err(|e| format!("create {}: {e}", to.display()))?;
    for entry in std::fs::read_dir(from).map_err(|e| format!("read {}: {e}", from.display()))? {
        let entry = entry.map_err(|e| e.to_string())?;
        let (src, dst) = (entry.path(), to.join(entry.file_name()));
        if entry.file_name() == "target" {
            continue;
        }
        if src.is_dir() {
            copy_tree(&src, &dst)?;
        } else {
            std::fs::copy(&src, &dst).map_err(|e| format!("copy {}: {e}", src.display()))?;
        }
    }
    Ok(())
}

/// A path a proposal may touch: relative, under `src/` or `seed/`.
fn check_path(p: &str) -> Result<PathBuf, String> {
    let path = Path::new(p);
    let ok_components = path.components().all(|c| matches!(c, std::path::Component::Normal(_)));
    if p.is_empty() || !ok_components {
        return Err(format!("`{p}`: paths are relative to kernel-src/, without `..`"));
    }
    if !(p.starts_with("src/") || p.starts_with("seed/")) {
        return Err(format!(
            "`{p}` cannot be changed: only files under src/ and seed/ (Cargo.toml, Cargo.lock and wit/ belong to the hypervisor)"
        ));
    }
    Ok(path.to_path_buf())
}

/// Applies `edits` and `files` from a proposal to the tree at `dir`.
/// Returns the paths touched.
fn apply_edits(dir: &Path, req: &Value) -> Result<Vec<String>, String> {
    let mut touched = Vec::new();
    let mut changed = false;
    for (i, e) in req["edits"].as_array().into_iter().flatten().enumerate() {
        let n = i + 1;
        let (Some(p), Some(old), Some(new)) = (e["path"].as_str(), e["old_str"].as_str(), e["new_str"].as_str()) else {
            return Err(format!("edit {n}: needs string `path`, `old_str` and `new_str`"));
        };
        let file = dir.join(check_path(p)?);
        let text = std::fs::read_to_string(&file).map_err(|_| format!("edit {n}: `{p}` does not exist in kernel-src/"))?;
        if old.is_empty() {
            return Err(format!("edit {n}: old_str is empty"));
        }
        match text.matches(old).count() {
            1 => {}
            0 => return Err(format!("edit {n}: old_str not found in `{p}` (it must match the file exactly, including whitespace)")),
            k => return Err(format!("edit {n}: old_str occurs {k} times in `{p}`; include more surrounding text so it is unique")),
        }
        let updated = text.replacen(old, new, 1);
        changed |= updated != text;
        std::fs::write(&file, updated).map_err(|e| format!("edit {n}: {e}"))?;
        touched.push(p.to_string());
    }
    if let Some(files) = req["files"].as_object() {
        for (p, content) in files {
            let content = content.as_str().ok_or(format!("files: `{p}` must map to a string"))?;
            let file = dir.join(check_path(p)?);
            let old = std::fs::read_to_string(&file).ok();
            changed |= old.as_deref() != Some(content);
            if let Some(parent) = file.parent() {
                std::fs::create_dir_all(parent).map_err(|e| e.to_string())?;
            }
            std::fs::write(&file, content).map_err(|e| format!("files: `{p}`: {e}"))?;
            touched.push(p.clone());
        }
    }
    if touched.is_empty() {
        return Err("give `edits` ([{path, old_str, new_str}]) and/or `files` ({path: content})".into());
    }
    if !changed {
        return Err("the edits change nothing".into());
    }
    touched.sort();
    touched.dedup();
    Ok(touched)
}

/// The part of compiler output worth showing: from the first error on.
fn compiler_errors(out: &str) -> String {
    let lines: Vec<&str> = out.lines().collect();
    let start = lines.iter().position(|l| l.starts_with("error")).unwrap_or(0);
    let text = lines[start..]
        .iter()
        .filter(|l| !l.trim_start().starts_with("Compiling ") && !l.trim_start().starts_with("Blocking "))
        .copied()
        .collect::<Vec<_>>()
        .join("\n");
    sandbox::truncate(text.trim(), COMPILER_OUTPUT_MAX)
}

/// A temporary state dir + work dir for testing a candidate; removed on drop.
struct ScratchDir(PathBuf);

impl ScratchDir {
    fn new() -> ScratchDir {
        static N: AtomicU32 = AtomicU32::new(0);
        let n = N.fetch_add(1, Ordering::Relaxed);
        let dir = std::env::temp_dir().join(format!("cmh-wasm-scratch-{}-{n}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        ScratchDir(dir)
    }
}

impl Drop for ScratchDir {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

