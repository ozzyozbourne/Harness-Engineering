//! Kernel images: versions of the guest crate, their lifecycle and its
//! journal events.
//!
//! v1 is the image built into the hypervisor binary. `propose_kernel`
//! creates vN: the live image's source plus the agent's edits, built with
//! cargo for wasm32-wasip2 (offline first, 2 jobs, in a sandbox where the
//! repository, the state dir and ~/.config are read-only or hidden), booted
//! in a scratch instance, self-tested, and run through a conformance
//! scenario. A candidate that passes becomes the `trial` image from the next
//! task on; after `soak` clean tasks it is `kept`. A trap, a boot failure or
//! a failed task during the trial reverts to the last kept image.

